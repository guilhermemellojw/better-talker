    private fun claim(
        id: String,
        text: String,
        type: ClaimType = ClaimType.FACTUAL_BIBLICAL,
    ): Claim = Claim(
        id = id,
        text = text,
        span = ClaimSpan(0, text.length),
        type = type,
    )

    private fun unit(
        id: String,
        text: String,
        kind: DocumentKind = DocumentKind.BIBLE,
        unit: String? = "v. 1",
        edition: String? = null,
        resolved: Boolean = true,
        waived: Boolean = false,
        partial: Boolean = false,
        truncated: Boolean = false,
        exposed: Boolean = true,
    ): EvidenceUnit = EvidenceUnit(
        item = EvidenceItem(
            id = id,
            reference = id,
            provenance = EvidenceProvenance(
                sourceId = id,
                category = kind.requiredCategory,
                documentUnit = unit,
                recoveredText = text,
                resolved = resolved,
                waived = waived,
                partial = partial,
            ),
        ),
        kind = kind,
        edition = edition,
        documentUnit = unit,
        truncated = truncated,
        exposedToModel = exposed,
    )

